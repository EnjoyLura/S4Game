"""Finish a Cocos MD5 production build. Only local build files are read/written."""
from pathlib import Path
import hashlib
import json
import re

GAME = Path(__file__).resolve().parents[1]
WEB = GAME / 'build/web-mobile'


def main():
    settings_path, = (WEB / 'src').glob('settings.*.json')
    settings = json.loads(settings_path.read_text(encoding='utf-8'))
    if settings['engine']['debug'] or not settings['assets'].get('bundleVers'):
        raise RuntimeError('Use tools/web-release-build.json (debug=false, md5Cache=true)')
    # The final DPR patch is applied after Cocos computes its filenames. Give all engine
    # imports an additional content revision, so changing that patch cannot retain old code.
    engines = sorted((WEB / 'cocos-js').glob('*.js'))
    engine_text = {path: path.read_text(encoding='utf-8') for path in engines}
    if not any('__KW_DPR_CAP' in source for source in engine_text.values()):
        raise RuntimeError('Run tools/patch-web-dpr.py first')
    # Strip only this script's own previous revision to make repeated preparation idempotent.
    strip_revision = lambda source: re.sub(r'\.js\?kwengine=[a-f0-9]{16}', '.js', source)
    normalized = {path: strip_revision(source) for path, source in engine_text.items()}
    digest = hashlib.sha256()
    for path, source in normalized.items():
        digest.update(path.name.encode('utf-8'))
        digest.update(source.encode('utf-8'))
    revision = digest.hexdigest()[:16]
    # Engine chunk imports are quoted relative paths. Keep SystemJS module names intact.
    names = {path.name for path in engines}
    def version_imports(source):
        source = strip_revision(source)
        def replace(match):
            value = match.group(2)
            if value.rsplit('/', 1)[-1] in names:
                value += '?kwengine=' + revision
            return match.group(1) + value + match.group(1)
        return re.sub(r'([\x22\x27])([^\x22\x27\r\n]+\.js)\1', replace, source)
    for path, source in normalized.items():
        path.write_text(version_imports(source), encoding='utf-8', newline='')
    import_map_path, = (WEB / 'src').glob('import-map.*.json')
    import_map_path.write_text(version_imports(import_map_path.read_text(encoding='utf-8')), encoding='utf-8', newline='')
    html_path = WEB / 'index.html'
    html = html_path.read_text(encoding='utf-8')
    pattern = re.escape(import_map_path.name) + r'(?:\?kwengine=[a-f0-9]{16})?'
    html, matches = re.subn(pattern, import_map_path.name + '?kwengine=' + revision, html)
    if matches != 1:
        raise RuntimeError('Expected exactly one import map in index.html')
    # Preload requests share the exact URL used by the engine. They only target startup code,
    # not textures, so optional images cannot displace the first visible page.
    start, = re.findall(r"System\.import\('\./([^']+)'\)", html)
    application_path, = WEB.glob('application.*.js')
    cc_path, = (WEB / 'cocos-js').glob('cc.*.js')
    virtual_path, = (WEB / 'cocos-js').glob('_virtual_cc-*.js')
    preloads = [(start, 'script'), (application_path.name, 'script'),
        ('src/' + settings_path.name, 'fetch'),
        ('cocos-js/' + cc_path.name + '?kwengine=' + revision, 'script'),
        ('cocos-js/' + virtual_path.name + '?kwengine=' + revision, 'script')]
    html = re.sub(r'\n  <!-- KW startup preloads -->[\s\S]*?<!-- /KW startup preloads -->\n', '\n', html)
    links = '\n  <!-- KW startup preloads -->\n' + '\n'.join(
        '  <link rel="preload" as="' + kind + '" href="' + url + '" crossorigin="anonymous">'
        for url, kind in preloads) + '\n  <!-- /KW startup preloads -->\n'
    html = html.replace('</head>', links + '</head>')
    html_path.write_text(html, encoding='utf-8', newline='')
    # Avoid global no-cache: overlapping Pages header values are joined, not overridden.
    # Conversely, never grant immutable caching to an unversioned resource directory.
    asset_paths = [path for path in (WEB / 'assets').rglob('*') if path.is_file()]
    unversioned = [path.relative_to(WEB).as_posix() for path in asset_paths
        if not any(re.search(r'\.[a-f0-9]{5,}(?:\.|$)', part) for part in path.relative_to(WEB).parts)]
    if unversioned:
        raise RuntimeError('Unversioned assets in immutable directory: ' + str(unversioned[:8]))
    headers = '''# Generated by tools/prepare-web-release.py; production MD5 build required.
# HTML always revalidates. Versioned code and assets can be reused without revalidation.
/
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=31536000, immutable
/cocos-js/*
  Cache-Control: public, max-age=31536000, immutable
/src/*.js
  Cache-Control: public, max-age=31536000, immutable
/src/*.json
  Cache-Control: public, max-age=31536000, immutable
/src/effect.bin
  Cache-Control: no-cache
/index.*.js
  Cache-Control: public, max-age=31536000, immutable
/application.*.js
  Cache-Control: public, max-age=31536000, immutable
/style.*.css
  Cache-Control: public, max-age=31536000, immutable
'''
    (WEB / '_headers').write_text(headers, encoding='utf-8', newline='')
    record = {'production': True, 'md5Cache': True, 'engineRevision': revision,
        'entry': start, 'immutableAssets': len(asset_paths), 'startupPreloads': preloads,
        'validation': 'offline preparation only; no game or browser executed'}
    (WEB / 'web-release.json').write_text(json.dumps(record, indent=2), encoding='utf-8')
    print(json.dumps(record))


if __name__ == '__main__':
    main()
